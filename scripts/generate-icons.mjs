/**
 * Builds resources/js/components/icons/index.tsx from icon-map.json.
 *
 * Each entry maps a component name to a Material Symbols Rounded file name
 * (weight 400; a "-fill" suffix picks the filled style, like Flutter's
 * Icons.*_rounded). Only the mapped icons end up in the bundle.
 *
 *     node scripts/generate-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = resolve(root, 'resources/js/components/icons');
const svgDir = resolve(root, 'node_modules/@material-symbols/svg-400/rounded');

const map = JSON.parse(readFileSync(resolve(iconsDir, 'icon-map.json'), 'utf8'));

const missing = [];
const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, file]) => {
        let svg;
        try {
            svg = readFileSync(resolve(svgDir, `${file}.svg`), 'utf8');
        } catch {
            missing.push(`${name} -> ${file}`);
            return null;
        }
        const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
        return `export const ${name} = /* @__PURE__ */ createIcon('${name}', ${JSON.stringify(paths.join(' '))});`;
    });

if (missing.length > 0) {
    console.error(`Missing Material Symbols:\n  ${missing.join('\n  ')}`);
    process.exit(1);
}

const output = `// Generated by scripts/generate-icons.mjs from icon-map.json. Do not edit by hand.
import { createIcon } from './create-icon';

export { type IconProps, type IconType } from './create-icon';

${entries.join('\n')}
`;

writeFileSync(resolve(iconsDir, 'index.tsx'), output);
console.log(`Wrote ${entries.length} icons.`);
